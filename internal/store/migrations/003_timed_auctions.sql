CREATE TABLE commerce_lot_auctions (
 lot_id TEXT PRIMARY KEY REFERENCES catalog_lots(id),
 event_id TEXT NOT NULL REFERENCES catalog_events(id),
 opens_at BIGINT NOT NULL CHECK(opens_at BETWEEN 0 AND 8640000000000000),
 closes_at BIGINT NOT NULL CHECK(closes_at > opens_at AND closes_at <= 8640000000000000),
 currency TEXT NOT NULL DEFAULT 'USD' CHECK(currency='USD'),
 starting_price_minor BIGINT NOT NULL CHECK(starting_price_minor BETWEEN 0 AND 1000000000000),
 bid_increment_minor BIGINT NOT NULL CHECK(bid_increment_minor BETWEEN 1 AND 1000000000000),
 state TEXT NOT NULL DEFAULT 'scheduled' CHECK(state IN ('scheduled','open','sold','unsold')),
 revision BIGINT NOT NULL DEFAULT 1 CHECK(revision > 0),
 bid_count BIGINT NOT NULL DEFAULT 0 CHECK(bid_count >= 0),
 leading_bid_id BIGINT,
 CHECK((bid_count=0) = (leading_bid_id IS NULL)),
 CHECK(state <> 'sold' OR leading_bid_id IS NOT NULL),
 CHECK(state <> 'unsold' OR leading_bid_id IS NULL)
);
CREATE INDEX commerce_auctions_due ON commerce_lot_auctions(state,closes_at,opens_at,lot_id) WHERE state IN ('scheduled','open');
CREATE TABLE commerce_bids (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lot_id TEXT NOT NULL REFERENCES commerce_lot_auctions(lot_id),
 account_id TEXT COLLATE "C" NOT NULL REFERENCES commerce_accounts(id),
 sequence BIGINT NOT NULL CHECK(sequence > 0),
 amount_minor BIGINT NOT NULL CHECK(amount_minor BETWEEN 0 AND 1000000000000),
 accepted_at BIGINT NOT NULL CHECK(accepted_at BETWEEN 0 AND 8640000000000000),
 request_id TEXT COLLATE "C" NOT NULL CHECK(request_id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
 bidder_number BIGINT NOT NULL CHECK(bidder_number > 0),
 UNIQUE(lot_id,sequence), UNIQUE(account_id,request_id),
 UNIQUE(lot_id,id), UNIQUE(lot_id,id,account_id,amount_minor)
);
ALTER TABLE commerce_lot_auctions ADD CONSTRAINT commerce_leading_bid FOREIGN KEY(lot_id,leading_bid_id) REFERENCES commerce_bids(lot_id,id);
CREATE INDEX commerce_bids_history ON commerce_bids(lot_id,sequence DESC);
CREATE INDEX commerce_bids_account ON commerce_bids(account_id,accepted_at DESC,lot_id);
CREATE TABLE commerce_auction_results (
 lot_id TEXT PRIMARY KEY REFERENCES commerce_lot_auctions(lot_id),
 outcome TEXT NOT NULL CHECK(outcome IN ('sold','unsold')),
 closes_at BIGINT NOT NULL CHECK(closes_at BETWEEN 0 AND 8640000000000000),
 recorded_at BIGINT NOT NULL CHECK(recorded_at >= closes_at AND recorded_at <= 8640000000000000),
 winning_bid_id BIGINT,
 winning_account_id TEXT COLLATE "C" REFERENCES commerce_accounts(id),
 winning_amount_minor BIGINT CHECK(winning_amount_minor BETWEEN 0 AND 1000000000000),
 CHECK((outcome='sold' AND winning_bid_id IS NOT NULL AND winning_account_id IS NOT NULL AND winning_amount_minor IS NOT NULL) OR
       (outcome='unsold' AND winning_bid_id IS NULL AND winning_account_id IS NULL AND winning_amount_minor IS NULL)),
 FOREIGN KEY(lot_id,winning_bid_id,winning_account_id,winning_amount_minor) REFERENCES commerce_bids(lot_id,id,account_id,amount_minor)
);
