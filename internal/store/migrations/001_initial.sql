CREATE TABLE catalog_lots (
 id TEXT PRIMARY KEY, slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
 category_id TEXT REFERENCES catalog_categories(id), description TEXT NOT NULL DEFAULT '', brand TEXT, era TEXT, story TEXT,
 condition TEXT NOT NULL DEFAULT '', specifications JSONB NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(specifications)='array'),
 fulfillment JSONB NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(fulfillment)='object'),
 starting_price_minor BIGINT CHECK(starting_price_minor BETWEEN 0 AND 1000000000000),
 bid_increment_minor BIGINT CHECK(bid_increment_minor BETWEEN 1 AND 1000000000000),
 currency TEXT NOT NULL DEFAULT 'USD' CHECK(currency='USD'),
 state TEXT NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','published')),
 admin_notes TEXT NOT NULL DEFAULT '', version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, demo BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE catalog_lot_images (
 lot_id TEXT NOT NULL REFERENCES catalog_lots(id), position INTEGER NOT NULL CHECK(position>=0),
 path TEXT NOT NULL, alt TEXT NOT NULL, PRIMARY KEY(lot_id,position)
);
CREATE TABLE catalog_events (
 id TEXT PRIMARY KEY, slug TEXT NOT NULL UNIQUE, title TEXT NOT NULL CHECK(length(btrim(title))>0),
 theme TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '', cover_path TEXT NOT NULL DEFAULT '', cover_alt TEXT NOT NULL DEFAULT '',
 opens_at BIGINT CHECK(opens_at BETWEEN 0 AND 8640000000000000),
 first_closes_at BIGINT CHECK(first_closes_at BETWEEN 0 AND 8640000000000000),
 close_interval_ms BIGINT CHECK(close_interval_ms BETWEEN 1 AND 8640000000000000),
 state TEXT NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','published')),
 admin_notes TEXT NOT NULL DEFAULT '', version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, demo BOOLEAN NOT NULL DEFAULT FALSE,
 CHECK(opens_at IS NULL OR first_closes_at IS NULL OR first_closes_at>opens_at)
);
CREATE TABLE catalog_event_lots (
 event_id TEXT NOT NULL REFERENCES catalog_events(id), lot_id TEXT NOT NULL UNIQUE REFERENCES catalog_lots(id),
 position INTEGER NOT NULL CHECK(position>=0), PRIMARY KEY(event_id,position)
);
CREATE TABLE catalog_seed_runs (version INTEGER PRIMARY KEY, reference_at BIGINT NOT NULL);
CREATE TABLE sqlite_import_runs (fingerprint TEXT PRIMARY KEY, source_version INTEGER NOT NULL CHECK(source_version=4), report_json TEXT NOT NULL, completed_at BIGINT NOT NULL);
