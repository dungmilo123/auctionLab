
CREATE TABLE IF NOT EXISTS players (
  id           TEXT COLLATE "C" PRIMARY KEY,
  nickname     TEXT COLLATE "C" NOT NULL UNIQUE,
  nickname_key TEXT COLLATE "C" NOT NULL,
  token        TEXT COLLATE "C" NOT NULL UNIQUE,
  budget       BIGINT NOT NULL,
  total_value  BIGINT NOT NULL DEFAULT 0,
  joined_at    BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_players_nickname_key ON players(nickname_key);

CREATE TABLE IF NOT EXISTS items (
  id                    TEXT COLLATE "C" PRIMARY KEY,
  order_index           BIGINT NOT NULL,
  name                  TEXT COLLATE "C" NOT NULL,
  description           TEXT COLLATE "C",
  image_url             TEXT COLLATE "C",
  auction_type          TEXT COLLATE "C" NOT NULL,
  truth_value           BIGINT NOT NULL,
  hint_min              BIGINT,
  hint_max              BIGINT,
  start_price           BIGINT NOT NULL,
  min_increment         BIGINT,
  floor_price           BIGINT,
  decrement_step        BIGINT,
  decrement_interval_ms BIGINT,
  duration_ms           BIGINT,
  anti_snipe_mode       TEXT COLLATE "C" DEFAULT 'disabled',
  anti_snipe_window_ms  BIGINT,
  max_extensions        BIGINT,
  status                TEXT COLLATE "C" NOT NULL DEFAULT 'pending'
);

CREATE TABLE IF NOT EXISTS sealed_bids (
  item_id      TEXT COLLATE "C" NOT NULL REFERENCES items(id),
  player_id    TEXT COLLATE "C" NOT NULL REFERENCES players(id),
  amount       BIGINT NOT NULL,
  submitted_at BIGINT NOT NULL,
  updated_at   BIGINT NOT NULL,
  PRIMARY KEY (item_id, player_id)
);

CREATE TABLE IF NOT EXISTS bids (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id    TEXT COLLATE "C" NOT NULL REFERENCES items(id),
  player_id  TEXT COLLATE "C" NOT NULL REFERENCES players(id),
  amount     BIGINT NOT NULL,
  kind       TEXT COLLATE "C" NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS auction_runtime (
  item_id         TEXT COLLATE "C" PRIMARY KEY REFERENCES items(id),
  started_at      BIGINT NOT NULL,
  deadline_at     BIGINT,
  settled_at      BIGINT,
  revision        BIGINT NOT NULL,
  extensions_used BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS game (
  id              BIGINT PRIMARY KEY CHECK (id = 1),
  phase           TEXT COLLATE "C" NOT NULL,
  current_item_id TEXT COLLATE "C" REFERENCES items(id),
  revision        BIGINT NOT NULL,
  config_json     TEXT COLLATE "C" NOT NULL,
  updated_at      BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type         TEXT COLLATE "C" NOT NULL,
  payload_json TEXT COLLATE "C",
  created_at   BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS server_config (
  key   TEXT COLLATE "C" PRIMARY KEY,
  value TEXT COLLATE "C" NOT NULL
);
